def to_pages(rows):
    h = len(rows)
    w = len(rows[0])
    assert all(len(r) == w for r in rows)
    out = []
    for p in range((h + 7) // 8):
        for x in range(w):
            b = 0
            for bit in range(8):
                y = p * 8 + bit
                if y < h and rows[y][x] == "#":
                    b |= 1 << bit
            out.append(b)
    return w, h, out


def c_bytes(data, per_line=16, indent="    "):
    lines = []
    for i in range(0, len(data), per_line):
        lines.append(indent + ", ".join("0x%02X" % b for b in data[i:i + per_line]) + ",")
    return "\n".join(lines)


def main():
    # fix ppg_pict row length
    w = max(len(r) for r in ICONS["ppg_pict"])
    ICONS["ppg_pict"] = [r.ljust(w, ".") for r in ICONS["ppg_pict"]]

    chars = [chr(c) for c in range(0x20, 0x7F)]
    small_bits = []
    small_w = []
    for ch in chars:
        rows = SMALL[ch]
        ww, hh, data = to_pages(rows)
        small_w.append(ww)
        small_bits.append(data + [0] * (5 - ww))
    for name, rows in EXTRA:
        rows = list(rows)
        while len(rows) < 8:
            rows.append("." * len(rows[0]))
        ww, hh, data = to_pages(rows)
        small_w.append(ww)
        small_bits.append(data + [0] * (5 - ww))
    n_small = len(small_bits)

    big = []
    for ch in BIG_ORDER:
        rows = BIG[ch]
        assert len(rows) == 14 and all(len(r) == 9 for r in rows), ch
        big.append(to_pages(rows)[2])

    h = []
    h.append("/* Generated by host/render/gen_assets.py - do not edit. */")
    h.append("#ifndef UI_ASSETS_H")
    h.append("#define UI_ASSETS_H")
    h.append("")
    h.append("#include <stdint.h>")
    h.append("")
    h.append("/* Small font: codes 0x20..0x%02X, 5 bytes per glyph (one page), widths */"
             % (0x20 + n_small - 1))
    h.append("#define FONT5_FIRST 0x20")
    h.append("#define FONT5_COUNT %d" % n_small)
    h.append("extern const uint8_t font5_bits[FONT5_COUNT][5];")
    h.append("extern const uint8_t font5_width[FONT5_COUNT];")
    h.append("/* UI glyphs as string literals (keep them separate literals). */")
    for i, (name, _) in enumerate(EXTRA):
        h.append('#define G_%s "\\x%02x"' % (name, EXTRA_FIRST + i))
    h.append("")
    h.append("/* Big digits 9 x 14: '0'..'9', '-', ' ' */")
    h.append("#define FONTBIG_W 9")
    h.append("#define FONTBIG_H 14")
    h.append("extern const uint8_t fontbig_bits[%d][18];" % len(big))
    h.append("")
    h.append("typedef struct { uint8_t w, h; const uint8_t *bits; } ui_icon_t;")
    for name in ICONS:
        h.append("extern const ui_icon_t icon_%s;" % name)
    h.append("")
    h.append("#endif")

    c = []
    c.append("/* Generated by host/render/gen_assets.py - do not edit. */")
    c.append('#include "ui_assets.h"')
    c.append("")
    c.append("const uint8_t font5_bits[FONT5_COUNT][5] = {")
    for i, d in enumerate(small_bits):
        code = 0x20 + i
        label = chr(code) if code < 0x7F else EXTRA[code - 0x7F][0]
        if label in ("\\",):
            label = "backslash"
        c.append("    {%s}, /* %s */" % (", ".join("0x%02X" % b for b in d), label))
    c.append("};")
    c.append("")
    c.append("const uint8_t font5_width[FONT5_COUNT] = {")
    c.append(c_bytes(small_w))
    c.append("};")
    c.append("")
    c.append("const uint8_t fontbig_bits[%d][18] = {" % len(big))
    for ch, d in zip(BIG_ORDER, big):
        c.append("    {%s}, /* '%s' */" % (", ".join("0x%02X" % b for b in d), ch))
    c.append("};")
    c.append("")
    for name, rows in ICONS.items():
        w_, h_, data = to_pages(rows)
        c.append("static const uint8_t icon_%s_bits[%d] = {" % (name, len(data)))
        c.append(c_bytes(data))
        c.append("};")
        c.append("const ui_icon_t icon_%s = {%d, %d, icon_%s_bits};" % (name, w_, h_, name))
        c.append("")

    with open(OUT_C, "w") as f:
        f.write("\n".join(c))
    with open(OUT_H, "w") as f:
        f.write("\n".join(h) + "\n")
    print("wrote", OUT_C, OUT_H, file=sys.stderr)


if __name__ == "__main__":
    main()
